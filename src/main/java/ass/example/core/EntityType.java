package ass.example.core;

/**
 * EntityType
 *
 * 遊戲中所有 Entity 的類型列表。
 *
 * 用途：
 * 1. 讓 Factory 建立 Entity 時設定 type。
 * 2. 讓系統透過 getEntitiesByType(...) 查找特定物件。
 * 3. 讓碰撞系統判斷碰撞對象。
 * 4. 讓場景系統分類管理 Entity。
 */
public enum EntityType {

    // =========================================================
    // Player
    // =========================================================

    /**
     * 玩家本體。
     */
    PLAYER,

    /**
     * 玩家腳底地面感測器。
     */
    PLAYER_GROUND_SENSOR,


    // =========================================================
    // Map / Environment
    // =========================================================

    /**
     * 地圖背景或視覺圖層。
     */
    MAP_BACKGROUND,

    /**
     * 一般牆壁。
     */
    WALL,

    /**
     * 地板。
     */
    FLOOR,

    /**
     * 一般平台。
     */
    PLATFORM,

    /**
     * 窗戶或窗外視差背景。
     */
    WINDOW,


    // =========================================================
    // Death / Hazard
    // =========================================================

    /**
     * 死亡區。
     *
     * 玩家碰到後會觸發死亡。
     */
    DEATH_ZONE,


    // =========================================================
    // One Way Platform
    // =========================================================

    /**
     * 一方通行平台入口。
     */
    ONE_WAY_PLATFORM,

    /**
     * 一方通行平台實體碰撞箱。
     */
    ONE_WAY_PLATFORM_COLLIDER,


    // =========================================================
    // Interaction / Props
    // =========================================================

    /**
     * 可互動物件。
     */
    INTERACTABLE,

    /**
     * 觸發區。
     */
    TRIGGER,

    /**
     * 純道具或裝飾物。
     */
    PROP,

    /**
     * 敵人。
     */
    ENEMY,

    /**
     * 可拾取或特殊物品。
     */
    ITEM,


    // =========================================================
    // HouseScene - Door
    // =========================================================

    /**
     * 家中一般門。
     */
    DOOR,

    /**
     * 門關閉時生成的阻擋碰撞箱。
     */
    DOOR_COLLIDER,


    // =========================================================
    // HouseScene - Bed
    // =========================================================

    /**
     * 床的一方通行入口平台。
     */
    BED_ONE_WAY_PLATFORM,

    /**
     * 床動態生成出的實體碰撞箱。
     */
    BED_ONE_WAY_PLATFORM_COLLIDER
}